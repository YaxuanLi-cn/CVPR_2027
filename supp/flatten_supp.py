"""Flatten the supplement into ONE self-contained supp.tex.

  python supp/flatten_supp.py [out_dir]        (default out_dir: /root/supp)

Reads docs/paper/supp/{supp.tex, numbers.tex, sec/*.tex, tables/*.tex}, inlines every \\input and replaces
every number macro of numbers.tex by its value, so that the result needs only supp.bib, cvpr.sty,
ieeenat_fullname.bst and figures/*.pdf next to it.
"""
import os
import re
import shutil
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs', 'paper', 'supp')
OUT = sys.argv[1] if len(sys.argv) > 1 else '/root/supp'

INPUT = re.compile(r'^([ \t]*)\\input\{([^}]+)\}[ \t]*$', re.M)
NEWCMD = re.compile(r'^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}$')
GENERATED = re.compile(r'^% generated by .*\n', re.M)


def read(rel):
    if not rel.endswith('.tex'):
        rel += '.tex'
    with open(os.path.join(SRC, rel)) as f:
        return f.read()


# ---- number macros
NUM = {}
for line in read('numbers').splitlines():
    m = NEWCMD.match(line)
    if m:
        NUM[m.group(1)] = m.group(2)
    else:
        assert line.startswith('%') or not line.strip(), line
for k, v in NUM.items():
    assert not re.search(r'\\[A-Za-z]+$', v), (k, v)          # a value must not end in a control word
    assert not any(re.search(r'\\' + n + r'(?![A-Za-z])', v) for n in NUM), (k, v)   # no nesting


def inline(text, depth=0):
    def sub(m):
        name = m.group(2)
        if name == 'numbers':
            return ''
        body = GENERATED.sub('', read(name)).strip('\n')
        body = inline(body, depth + 1)
        if name.startswith('sec/'):
            bar = '% ' + '=' * 100
            return f'{bar}\n% {name}\n{bar}\n{body}\n'
        return body
    return INPUT.sub(sub, text)


used = set()


def expand(text):
    """Replace \\name by its value. TeX skips blanks (and one line end) after a control word, so they are
    removed here as well, which keeps the typeset output identical."""
    def sub(m):
        name = m.group(1)
        if name not in NUM:
            return m.group(0)
        used.add(name)
        return NUM[name]
    return re.sub(r'\\([A-Za-z]+)(?![A-Za-z])(?:[ \t]*\n?[ \t]*)?', lambda m: sub(m) if m.group(1) in NUM else m.group(0),
                  text)


tex = read('supp')
head = ('% Supplementary material for the CVPR 2027 submission\n'
        '% "Last-Meter Precision Navigation for UAVs: A Geometric Imagination-Based Aerial Visual Servoing Approach"\n'
        '% Single-file version. Needs next to it: supp.bib, cvpr.sty, ieeenat_fullname.bst, figures/*.pdf\n'
        '% Build:  pdflatex supp && bibtex supp && pdflatex supp && pdflatex supp\n')
tex = head + tex[tex.index('\\documentclass'):]
tex = expand(inline(tex))
assert '\\input{' not in tex, re.findall(r'\\input\{[^}]+\}', tex)
tex = re.sub(r'(?<=[0-9])\{\}(?=[ \n])', '', tex)      # '2.2{} points' -> '2.2 points'
tex = re.sub(r'\n{3,}', '\n\n', tex)

os.makedirs(os.path.join(OUT, 'figures'), exist_ok=True)
with open(os.path.join(OUT, 'supp.tex'), 'w') as f:
    f.write(tex)
for fn in ('supp.bib', 'cvpr.sty', 'ieeenat_fullname.bst'):
    shutil.copy2(os.path.join(SRC, fn), os.path.join(OUT, fn))
for fig in sorted(set(re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}', tex))):
    shutil.copy2(os.path.join(SRC, fig), os.path.join(OUT, fig))
print(f'{os.path.join(OUT, "supp.tex")}: {tex.count(chr(10))} lines, {len(used)} of {len(NUM)} number macros expanded')
